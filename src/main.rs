use axum::{
    extract::State,
    routing::{get, post},
    Json, Router,
};
use serde::{Deserialize, Serialize};
use std::{
    env,
    sync::{Arc, Mutex},
};
use tower_http::{cors::CorsLayer, services::ServeDir};

#[derive(Debug, Clone, Serialize, Deserialize)]
struct PartNode {
    id: String,
    shape: String,         // "Block", "Cylinder", "Sphere", "Wedge", "MeshRig"
    size: [f32; 3],        // Roblox Studs: [X, Y, Z]
    position: [f32; 3],    // 3D coordinates: [X, Y, Z]
    color: String,         // Hex color
    material: String,      // "Plastic", "Neon", "Metal", "ForceField"
    semantic_role: String, // What this part actually means & does
}

#[derive(Debug, Clone, Serialize, Deserialize)]
struct JointLink {
    source: String,
    target: String,
    joint_type: String, // "Motor6D", "WeldConstraint", "SemanticLink"
}

#[derive(Debug, Clone, Default, Serialize, Deserialize)]
struct BrainGraph {
    nodes: Vec<PartNode>,
    links: Vec<JointLink>,
    luau_script: String,
}

#[derive(Debug, Deserialize)]
struct PromptRequest {
    prompt: String,
}

type SharedBrain = Arc<Mutex<BrainGraph>>;

fn generate_luau_script(nodes: &[PartNode], links: &[JointLink]) -> String {
    let mut script = String::from("-- Generated by NEUROPIL 3D Semantic Brain\nlocal model = Instance.new(\"Model\")\nmodel.Name = \"NeuropilGeneratedRig\"\nmodel.Parent = workspace\nlocal parts = {}\n\n");

    for n in nodes {
        script.push_str(&format!(
            "-- Role: {}\nlocal p_{} = Instance.new(\"Part\")\np_{}.Name = \"{}\"\np_{}.Size = Vector3.new({:.1}, {:.1}, {:.1})\np_{}.Position = Vector3.new({:.1}, {:.1}, {:.1})\np_{}.Color = Color3.fromHex(\"{}\")\np_{}.Material = Enum.Material.{}\np_{}.Anchored = true\np_{}.Parent = model\nparts[\"{}\"] = p_{}\n\n",
            n.semantic_role,
            n.id.replace(' ', "_"),
            n.id.replace(' ', "_"), n.id,
            n.id.replace(' ', "_"), n.size[0], n.size[1], n.size[2],
            n.id.replace(' ', "_"), n.position[0], n.position[1], n.position[2],
            n.id.replace(' ', "_"), n.color,
            n.id.replace(' ', "_"), n.material,
            n.id.replace(' ', "_"),
            n.id.replace(' ', "_"),
            n.id, n.id.replace(' ', "_")
        ));
    }

    for l in links {
        script.push_str(&format!(
            "local weld = Instance.new(\"WeldConstraint\")\nweld.Part0 = parts[\"{}\"]\nweld.Part1 = parts[\"{}\"]\nweld.Parent = parts[\"{}\"]\n",
            l.source, l.target, l.source
        ));
    }
    script
}

